// Writes src/render/vars.css: for every responsive value, picks desktop, tablet
// or phone by the page container's width. Run after adding a name below:
//   node scripts/gen-vars.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** Block-level values. Sections use the `s-` names so blocks never inherit a section's value by accident. */
const BLOCK = [
  "cols", "gap", "ar", "isw", "isf", "size", "x", "y", "w", "h", "rot", "z", "op", "fit", "sc", "sr", "align", "pos", "rh", "bcols", "brows", "bar", "gc", "gr",
  // Design tab: style, type, transforms
  "rad", "bbg", "pad", "bdr", "shd", "blend", "mw", "mt", "mb", "srot", "scl", "fs", "fw", "lh", "ls", "tc", "tt", "fst", "par",
];
const SECTION = ["s-sw", "s-gap", "s-rgap", "s-cols", "s-dir", "s-just", "s-ai", "s-wrap", "s-pt", "s-pb", "s-ar", "s-align"];
const all = [...BLOCK, ...SECTION];
const rules = (fn) => all.map(fn).join("\n    ");

const css = `/* Generated by scripts/gen-vars.mjs. Do not edit by hand. See src/render/responsive.ts. */
.sp-r {
    ${rules((v) => `--_${v}: var(--${v});`)}
}
@container sp-page (max-width: 1279.98px) {
  .sp-r {
    ${rules((v) => `--_${v}: var(--${v}-t, var(--${v}));`)}
  }
}
@container sp-page (max-width: 767.98px) {
  .sp-r {
    ${rules((v) => `--_${v}: var(--${v}-p, var(--${v}-t, var(--${v})));`)}
  }
}
`;

writeFileSync(fileURLToPath(new URL("../src/render/vars.css", import.meta.url)), css);
console.log(`vars.css: ${all.length} responsive values`);
